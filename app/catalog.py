ORDER = {sid: i for i, sid in enumerate(NAMES)}
# Two code prefixes are used by two subjects each in the official standards: 12심독 (심화 영어 독해와 작문,
# 심화 독일어) and 12스문 (스포츠 문화, 스페인어권 문화), so 11 codes repeat. The sheet's first block keeps the
# plain code; the second block's standards are keyed "[code] (과목명)" under their own subject id.
SECOND = {'12심독': '12심독-독', '12스문': '12스문-스'}
SECOND_BY_NAME = {(base, NAMES[alt]): alt for base, alt in SECOND.items()}
# 중학교 사회 codes name their area inside the prefix — [9사(지리)01-01], [9사(일사)01-01] — but both are one subject.
AREA = re.compile(r'\((?:지리|일사)\)$')
CODE = r'\[(\d+)([^0-9]+)(\d+)-(\d+)(?:-(\d+))?\]'

def subject_id(code):
    m=re.fullmatch(CODE+r'(?: \((.+)\))?',code)
    if not m: return ''
    # 미적분Ⅰ·영어Ⅰ처럼 로마 숫자로 끝나는 과목은 [12미적Ⅰ-01-01] 로 쓴다.
    sid=m[1]+AREA.sub('',m[2]).rstrip('-')+(m[3] if m[5] else '')
    return SECOND_BY_NAME.get((sid,m[6]),'') if m[6] else sid

def official_code(key):
    """The code as printed in the curriculum, without the subject added to tell repeated codes apart."""
    m=re.match(CODE,key or '')
    return m[0] if m else (key or '')

def standard_key(code, sid):
    return f'{code} ({NAMES[sid]})' if sid in SECOND.values() else code

def subject_name(sid):
    # Unmapped labels expose the original code instead of inventing a subject name.
    return NAMES.get(sid, f'기타 과목 · {sid}')

def subjects(catalog):
    groups={}
    for code in catalog:
        sid=subject_id(code)
        if sid:
            group=groups.setdefault(sid,{'id':sid,'name':subject_name(sid),'group':GROUP_OF.get(sid,'기타'),'count':0})
            group['count']+=1
    return sorted(groups.values(),key=lambda s:ORDER.get(s['id'],len(ORDER)))

def infer_subject(cards):
    ids={subject_id(c.get('standard','')) for c in cards if c.get('standard')}
    return next(iter(ids)) if len(ids)==1 else ''
